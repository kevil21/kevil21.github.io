/**
 * Generates public-facing dist/sw.js AFTER the build (postbuild): precaches the shell (home, offline, 404, résumé,
 * contact, their CSS/JS, fonts, manifest, icons, generated knowledge/answer/skill indexes), names the cache by the
 * SHA-256 of the precache list, serves HTML network-first with the offline fallback and assets cache-first.
 * It never intercepts /models/ (ORT/MiniLM/WebLLM downloads are cached by the browser/HF caches themselves).
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const DIST = join(ROOT, 'dist');

function walk(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

export function buildPrecacheList(dist = DIST): string[] {
  const pages = ['/', '/offline/', '/resume/', '/contact/', '/work/', '/certifications/', '/operator/'];
  const set = new Set<string>(['/404.html', '/manifest.webmanifest', '/favicon.svg']);
  for (const p of pages) {
    const file = join(dist, p === '/' ? 'index.html' : `${p.replace(/^\//, '')}index.html`);
    if (!existsSync(file)) continue;
    set.add(p);
    const html = readFileSync(file, 'utf8');
    for (const m of html.matchAll(/(?:href|src)="(\/_astro\/[^"]+)"/g)) set.add(m[1]!);
    for (const m of html.matchAll(/href="(\/images\/derived\/[^"]+)"/g)) set.add(m[1]!);
  }
  for (const f of walk(join(dist, '_astro')).filter((f) => /\.(woff2)$/.test(f)))
    set.add('/' + relative(dist, f));
  for (const f of [
    '/generated/knowledge-index.json',
    '/generated/answer-index.json',
    '/generated/skill-graph.json',
    '/generated/ai-manifest.json',
  ])
    if (existsSync(join(dist, f))) set.add(f);
  if (existsSync(join(dist, 'icons')))
    for (const f of walk(join(dist, 'icons'))) set.add('/' + relative(dist, f));
  // never precache the 3D or AI chunks: they are lazy and large
  return [...set]
    .filter((u) => !/three\.|mount\.|rapier|pocket\.worker|llm\.worker|semantic-index|\/models\//.test(u))
    .sort();
}

export function serviceWorkerSource(precache: string[], version: string): string {
  return `/* kevilpatel.in service worker · ${version} · generated by scripts/build-service-worker.ts */
const VERSION = ${JSON.stringify(version)};
const SHELL = 'sr-shell-' + VERSION;
const RUNTIME = 'sr-runtime-' + VERSION;
const PRECACHE = ${JSON.stringify(precache)};
const OFFLINE = '/offline/';

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== SHELL && k !== RUNTIME).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/models/') || url.pathname.includes('semantic-index')) return; // large, lazy, browser-cached
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          // Only successful pages are kept for offline use: never cache a 404 or a server error as the page.
          if (res.ok) {
            const copy = res.clone();
            caches.open(RUNTIME).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => caches.match(req).then((hit) => hit || caches.match(OFFLINE))),
    );
    return;
  }
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && (url.pathname.startsWith('/_astro/') || url.pathname.startsWith('/images/') || url.pathname.startsWith('/generated/'))) {
            const copy = res.clone();
            caches.open(RUNTIME).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
}

if (process.argv[1] && /build-service-worker\.ts$/.test(process.argv[1])) {
  const list = buildPrecacheList();
  const hash = createHash('sha256').update(list.join('\n')).digest('hex').slice(0, 10);
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')) as { version: string };
  const version = `${pkg.version}-${hash}`;
  writeFileSync(join(DIST, 'sw.js'), serviceWorkerSource(list, version));
  console.log(`✔ service worker: ${list.length} precached entries, cache ${version} → dist/sw.js`);
}
